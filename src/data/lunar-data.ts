/**
 * 获取农历年份信息
 */
export interface LunarYearInfo {
  /** 年份 */
  year: number;
  /** 闰月月份（0表示无闰月） */
  leapMonth: number;
  /** 闰月是否大月 */
  leapMonthBig: boolean;
  /** 每月天数数组 */
  monthDays: number[];
  /** 全年总天数 */
  totalDays: number;
}

/**
 * 解析农历年份数据
 */
export function parseLunarYear(year: number): LunarYearInfo {
  const yearData = LUNAR_YEAR_DATA[year];
  if (!yearData) {
    throw new Error(`不支持的年份: ${year}，仅支持1900-2100年`);
  }

  // 提取闰月信息（第13-16位）
  const leapMonth = (yearData >> 13) & 0x0f;
  // 提取闰月大小（第17位）
  const leapMonthBig = ((yearData >> 16) & 0x01) === 1;

  // 提取12个月的大小月信息（低12位）
  const monthDays: number[] = [];
  for (let i = 0; i < 12; i++) {
    const isBigMonth = ((yearData >> i) & 0x01) === 1;
    monthDays.push(isBigMonth ? 30 : 29);
  }

  // 计算总天数
  let totalDays = monthDays.reduce((sum, days) => sum + days, 0);
  if (leapMonth > 0) {
    totalDays += leapMonthBig ? 30 : 29;
  }

  return {
    year,
    leapMonth,
    leapMonthBig,
    monthDays,
    totalDays
  };
}

/**
 * 获取春节日期
 */
export function getLunarNewYear(year: number): { month: number; day: number } {
  const dateData = LUNAR_NEW_YEAR[year];
  if (!dateData) {
    throw new Error(`不支持的年份: ${year}，仅支持1900-2100年`);
  }

  const month = (dateData >> 8) & 0xff;
  const day = dateData & 0xff;

  return { month, day };
}
