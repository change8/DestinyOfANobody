/**
 * 八卦基本信息
 */
export interface BaGuaInfo {
  name: BaGua;
  index: number;
  trigram: string;  // 卦符
  nature: string;   // 五行
  yinyang: string;  // 阴阳
}

/**
 * 八卦类象信息
 */
export interface BaGuaXiang {
  // 基本属性
  gua: BaGua;
  五行: string;
  阴阳: string;
  卦符: string;

  // 物象
  物象: {
    形状: string[];
    颜色: string[];
    质地: string[];
    特征: string[];
    物品: string[];
  };

  // 方位
  方位: string;

  // 位置
  位置: {
    高低: string;
    内外: string;
    具体: string[];
  };

  // 人物
  人物: string[];

  // 动物
  动物: string[];

  // 身体
  身体部位: string[];

  // 时间
  时间特征: string;

  // 数字
  数字: number[];

  // 天气
  天象: string[];
}

