/**
 * 字义分析结果
 */
export interface CharAnalysisResult {
  // 基本信息
  character: string;
  笔画数: number;

  // 结构分析
  结构: CharStructure;
  部首?: string;
  部首信息?: {
    五行: '金' | '木' | '水' | '火' | '土';
    象征: string[];
    相关卦: BaGua[];
  };

  // 语义分析
  语义?: {
    含义: string[];
    象征: string[];
    相关卦: BaGua[];
    五行倾向?: '金' | '木' | '水' | '火' | '土';
  };

  // 综合判断
  建议卦象: BaGua[];
  分析说明: string;
}

/**
 * 提取字的部首
 */
export function extractRadical(char: string): string | undefined {
  // 简化实现：检查常见部首
  for (const radical of Object.keys(RADICAL_WUXING)) {
    if (char.includes(radical)) {
      return radical;
    }
  }

  // 特殊处理：检查字本身是否是部首
  if (RADICAL_WUXING[char]) {
    return char;
  }

  return undefined;
}

/**
 * 分析字的结构
 */
export function analyzeStructure(char: string): CharStructure {
  // 简化实现：基于常见字的结构
  const structures: Record<string, CharStructure> = {
    '找': '左右结构',
    '家': '上下结构',
    '钥': '左右结构',
    '匙': '左右结构',
    '机': '左右结构',
    '水': '独体字',
    '火': '独体字',
    '人': '独体字',
    '国': '全包围',
    '问': '半包围',
    '意': '上中下',
    '树': '左中右'
  };

  return structures[char] || '独体字';
}

/**
 * 综合分析字义
 */
export function analyzeCharacter(char: string, strokeCount?: number): CharAnalysisResult {
  const structure = analyzeStructure(char);
  const radical = extractRadical(char);
  const radicalInfo = radical ? RADICAL_WUXING[radical] : undefined;
  const semantics = CHAR_SEMANTICS[char];

  // 综合判断建议卦象
  const suggestedGua: BaGua[] = [];
  let analysis = `分析"${char}"字：\n`;

  // 1. 从语义分析
  if (semantics) {
    suggestedGua.push(...semantics.相关卦);
    analysis += `【语义】${semantics.含义.join('、')}，象征${semantics.象征.join('、')}，对应${semantics.相关卦.join('、')}卦。\n`;
  }

  // 2. 从部首分析
  if (radicalInfo) {
    suggestedGua.push(...radicalInfo.相关卦);
    analysis += `【部首】${radical}旁，五行属${radicalInfo.五行}，象征${radicalInfo.象征.join('、')}，对应${radicalInfo.相关卦.join('、')}卦。\n`;
  }

  // 3. 从结构分析
  if (structure === '左右结构') {
    analysis += `【结构】左右结构，有分离、对立之象。\n`;
  } else if (structure === '上下结构') {
    analysis += `【结构】上下结构，有上下、高低之分。\n`;
  } else if (structure === '独体字') {
    analysis += `【结构】独体字，象征完整、单一。\n`;
  }

  // 去重
  const uniqueGua = [...new Set(suggestedGua)];

  return {
    character: char,
    笔画数: strokeCount || char.length, // 简化实现
    结构: structure,
    部首: radical,
    部首信息: radicalInfo,
    语义: semantics,
    建议卦象: uniqueGua.length > 0 ? uniqueGua : ['震'], // 默认震卦
    分析说明: analysis
  };
}

/**
 * 多字综合分析
 */
export function analyzeMultipleChars(chars: string[]): {
  individual: CharAnalysisResult[];
  combined: {
    整体含义: string;
    主要卦象: BaGua[];
    综合分析: string;
  };
} {
  const individual = chars.map(char => analyzeCharacter(char));

  // 提取所有建议卦象
  const allGua = individual.flatMap(r => r.建议卦象);
  const guaCount = allGua.reduce((acc, gua) => {
    acc[gua] = (acc[gua] || 0) + 1;
    return acc;
  }, {} as Record<BaGua, number>);

  // 按出现频率排序
  const sortedGua = Object.entries(guaCount)
    .sort((a, b) => b[1] - a[1])
    .map(([gua]) => gua as BaGua);

  let combinedAnalysis = `综合分析"${chars.join('')}"：\n`;
  combinedAnalysis += individual.map((r, i) => `${i + 1}. ${r.分析说明}`).join('\n');
  combinedAnalysis += `\n【综合】主要卦象为${sortedGua.slice(0, 3).join('、')}。`;

  return {
    individual,
    combined: {
      整体含义: chars.join(''),
      主要卦象: sortedGua.slice(0, 3),
      综合分析: combinedAnalysis
    }
  };
}
